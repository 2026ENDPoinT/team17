def interview(text):
    return has_interview(text)


def grades(text):
    return extract_eligibility(text)["grades"]


def gpa(text):
    return extract_eligibility(text)["gpa_min"]


def score(text):
    return extract_eligibility(text)["score_min"]


def income(text):
    return extract_eligibility(text)["income_max"]


def amount(text):
    return extract_amount(text)[0]["value"]


def departments(text):
    return extract_departments(text)[0]


def departments_unclear(text):
    """입력: 본문 한 줄 / 출력: (학과 목록, 확인 필요 여부)"""
    found = extract_departments(text)
    return found[0], found[1]


def residence(text):
    return extract_residence("", text)[0]


def deadline(text):
    """입력: "본문 한 줄|게시일" """
    line, posted = text.rsplit("|", 1)
    return extract_deadline("", line, date.fromisoformat(posted))[0]


def token_kinds(text):
    return [t.kind for t in tokenize(text)]


def hourly_kind(text):
    return extract_amount(text)[0]["type"]


def deadline_text(text):
    """입력: "본문 한 줄|게시일" """
    line, posted = text.rsplit("|", 1)
    return extract_deadline("", line, date.fromisoformat(posted))[1]


def name(title):
    return extract_name(title)


def title_deadline(text):
    """입력: "제목|게시일" """
    title, posted = text.rsplit("|", 1)
    return extract_deadline(title, "", date.fromisoformat(posted))[0]


def form_docs(names):
    """입력: 양식 첨부 이름들 ("|"로 나눔)"""
    return documents_from_names(names.split("|"))


def docs(text):
    """입력: 공고문 텍스트 (줄은 "\\n")"""
    return extract_documents(text)


def conditions(text):
    """입력: 자격 문단의 줄들 (줄은 "\\n")"""
    return conditions_from_block(text.split("\n"), None)


def label(title):
    return classify_label(title, classify_kind(title)[0])[0]



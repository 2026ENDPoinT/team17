"""공지 텍스트에서 개인정보를 지운다. 입력: 문자열 / 출력: 지운 문자열.

- 이메일·전화번호 → [연락처]
- 학번 → [학번]
- 마스킹된 이름(홍*동, 홍○동) → [이름]
- 결과 공지의 이름 나열("선발결과 : 홍길동, 김철수 (이상 2명)") → [명단 삭제]
  선발·합격·명단 같은 단어가 있는 줄에서, 쉼표로 이어진 2~4글자 한글 단어 2개 이상만 지운다.
  다른 모양의 명단(표, 줄마다 한 명)은 못 잡을 수 있어 검수 때 확인한다.
"""

import re

_PATTERNS = [
    # 이메일
    (re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+"), "[연락처]"),
    # 일반·휴대전화 (02-970-1234, 010 1234 5678, +82-2-...)
    (re.compile(r"(?:\+82[-\s]?)?\(?0\d{1,2}\)?[-.\s]?\d{3,4}[-.\s]\d{4}"), "[연락처]"),
    # 대표번호 (1599-2290)
    (re.compile(r"\b1[5-9]\d{2}-\d{4}\b"), "[연락처]"),
    # 내선 (☎6054, 내선 6054, TEL: 6054)
    (re.compile(r"(?:☎|내선|[Tt][Ee][Ll]\.?)\s*[:：]?\s*\d[\d-]{2,}"), "[연락처]"),
    # 학번 (8자리, 1·2로 시작)
    (re.compile(r"(?<![\d,])[12]\d{7}(?![\d,])"), "[학번]"),
    # 마스킹된 이름: 가운데 글자를 가린 3글자 (홍*동). "필참*" 같은 강조 표시는 건드리지 않는다
    (re.compile(r"(?<![가-힣])[가-힣][*＊○◯●Ｏ][가-힣](?![가-힣])"), "[이름]"),
]

# 명단 줄로 볼 표현. "미선발자", "수혜자는" 같은 일반 문장에 걸리지 않게 좁게 잡는다.
_LIST_LINE = re.compile(r"(?:선발|선정|합격)\s*결과\s*[:：]|(?:선발|선정|합격)자\s*(?:명단)?\s*[:：]|명단\s*[:：]|이상\s*\d+\s*명")
# 쉼표로 이어진 이름 2개 이상. 목록이 줄 끝이나 "(이상 N명)", "외 N명" 앞에서 끝날 때만 지운다.
_NAME_LIST = re.compile(
    r"(?<![가-힣])[가-힣]{2,4}(?:\s*[,，、]\s*[가-힣]{2,4})+(?![가-힣])(?=\s*(?:$|\(|외\s*\d|등\s*\d))"
)


def _scrub_name_lists(text: str) -> str:
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if _LIST_LINE.search(line):
            lines[i] = _NAME_LIST.sub("[명단 삭제]", line)
    return "\n".join(lines)


def scrub(text: str) -> str:
    for pattern, repl in _PATTERNS:
        text = pattern.sub(repl, text)
    return _scrub_name_lists(text)

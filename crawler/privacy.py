"""공지 텍스트에서 개인정보를 지운다. 입력: 문자열 / 출력: 지운 문자열.

이메일·전화번호 → [연락처], 학번 → [학번], 마스킹된 이름(홍*동, 홍○동) → [이름]
마스킹되지 않은 이름 명단은 패턴으로 찾기 어려워 여기서 잡지 못한다. 결과·선발 공지는 분류 단계에서 빼고, 검수 때 확인한다.
"""

import re

_PATTERNS = [
    # 이메일
    (re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+"), "[연락처]"),
    # 일반·휴대전화 (02-970-1234, 010 1234 5678, +82-2-...)
    (re.compile(r"(?:\+82[-\s]?)?\(?0\d{1,2}\)?[-.\s]?\d{3,4}[-.\s]\d{4}"), "[연락처]"),
    # 대표번호 (1599-2290)
    (re.compile(r"\b1[5-9]\d{2}-\d{4}\b"), "[연락처]"),
    # 내선 (☎6054, 내선 6054, TEL: 6054)
    (re.compile(r"(?:☎|내선|[Tt][Ee][Ll]\.?)\s*[:：]?\s*\d[\d-]{2,}"), "[연락처]"),
    # 학번 (8자리, 1·2로 시작)
    (re.compile(r"(?<![\d,])[12]\d{7}(?![\d,])"), "[학번]"),
    # 마스킹된 이름
    (re.compile(r"[가-힣][*＊○◯●Ｏ][가-힣]{0,2}"), "[이름]"),
]


def scrub(text: str) -> str:
    for pattern, repl in _PATTERNS:
        text = pattern.sub(repl, text)
    return text
